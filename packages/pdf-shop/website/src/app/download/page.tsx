import { redirect } from 'next/navigation'
import { PageShell, Card, Heading, Subheading } from '@/lib/shared/ui'
import { getGeneratedDocumentStatus } from '@/lib/generated-documents/GeneratedDocumentStatus.server'
import { DownloadStatusPoller } from './download-status-poller'

export default async function DownloadPage({
  searchParams,
}: {
  searchParams: Promise<{ specId?: string }>
}) {
  const { specId } = await searchParams
  if (!specId) {
    redirect('/spec')
  }

  const status = await getGeneratedDocumentStatus(specId)
  const ready = Boolean(status?.paid && status.pdf)

  return (
    <PageShell>
      <Card>
        <Heading>Your document</Heading>
        <Subheading>
          Payment received. Your document is being generated by our processing
          pipeline.
        </Subheading>
        <DownloadStatusPoller specId={specId} initialReady={ready} />
      </Card>
    </PageShell>
  )
}
