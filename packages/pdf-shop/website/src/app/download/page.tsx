import { redirect } from 'next/navigation'

import { handleGetGeneratedDocumentReady } from '@org/pdf-shop-application'

import { PageShell, Card, Heading, Subheading } from '@/lib/ui'
import { pinoLogger } from '@/lib/pino'

import { DownloadStatusPoller } from './download-status-poller'

const handler = handleGetGeneratedDocumentReady({
  dataRoot: process.env.DATA_ROOT ?? '',
  logger: pinoLogger,
})

export default async function DownloadPage({
  searchParams,
}: {
  searchParams: Promise<{ documentId?: string }>
}) {
  const { documentId } = await searchParams
  if (!documentId) {
    redirect('/spec')
  }
  let status: boolean | null = null
  try {
    status = await handler({ documentId })
  } catch (err) {
    console.warn(err)
    status = null
  }
  const ready = Boolean(status)

  return (
    <PageShell>
      <Card>
        <Heading>Your document</Heading>
        <Subheading>
          Payment received. Your document is being generated by our processing
          pipeline.
        </Subheading>
        <DownloadStatusPoller documentId={documentId} initialReady={ready} />
      </Card>
    </PageShell>
  )
}
